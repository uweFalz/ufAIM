#!/usr/bin/env node
// tools/transed/bundle.mjs
//
// The single-file TransEd playground: transed/index.html, app.js and every
// module they reach under src/ folded into one HTML file that runs from a
// double-click, file:// included. It uses the module registry of the AXTRAN2
// bundle (tools/axtran2/bundle.mjs) and offers the same interface: output at
// the repository root, SHA-256 source manifest in the file, and --check.
// There is no worker here.
//
//   node tools/transed/bundle.mjs [--out dist/transed.html] [--check]

import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve, relative, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

import { escapeForHtml, graph, idOf, registry } from "../axtran2/bundle.mjs";

const ROOT = fileURLToPath(new URL("../../", import.meta.url));
const SCRIPT_TAG = '<script type="module" src="./app.js"></script>';
const TITLE_TAG = "<title>TransEd</title>";
const sha256 = (data) => createHash("sha256").update(data).digest("hex");

export async function bundleTransEd({ out = join(ROOT, "transed.html"), check = false } = {}) {
	const entry = join(ROOT, "transed/app.js");
	const pageFile = join(ROOT, "transed/index.html");
	const page = await readFile(pageFile, "utf8");
	if (!page.includes(SCRIPT_TAG) || !page.includes(TITLE_TAG)) throw new Error("the page's script or title tag was not found");
	const app = await graph([entry]);
	// every file the artifact is made from: modules, page, and both bundler files
	const sourceFiles = [...new Set([...app.order, pageFile, fileURLToPath(import.meta.url), join(ROOT, "tools/axtran2/bundle.mjs")])].sort();
	const sources = {};
	for (const file of sourceFiles) sources[idOf(file)] = sha256(await readFile(file));
	const sourceHash = sha256(JSON.stringify(sources));
	const script = `${registry(app.modules, app.order)}\n__require(${JSON.stringify(idOf(entry))});`;
	const html = page
		.replace(SCRIPT_TAG, () => `<script>\n${escapeForHtml(script)}\n</script>`)
		.replace(TITLE_TAG, () => `${TITLE_TAG}\n<!-- Generated by tools/transed/bundle.mjs; edit modular sources, not this file. -->\n<meta name="transed-source-sha256" content="${sourceHash}">\n<!-- transed-source-manifest ${JSON.stringify(sources)} -->`);
	if (check) {
		let existing = null;
		try { existing = await readFile(out, "utf8"); } catch { /* reported below */ }
		if (existing !== html) throw new Error(`${out}: stale TransEd artifact; run npm run bundle:transed from the common repository`);
	} else {
		await mkdir(dirname(out), { recursive: true });
		await writeFile(out, html);
	}
	return Object.freeze({ out, modules: app.order.length, bytes: Buffer.byteLength(html), sourceHash, sources, checked: check });
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	const outArg = process.argv.indexOf("--out");
	bundleTransEd({ ...(outArg > 0 ? { out: resolve(process.argv[outArg + 1]) } : {}), check: process.argv.includes("--check") })
		.then((r) => console.log(`${relative(process.cwd(), r.out)}: ${r.modules} modules, ${(r.bytes / 1024).toFixed(0)} KB, source ${r.sourceHash.slice(0, 12)}${r.checked ? ", up to date" : ""}`))
		.catch((e) => { console.error(e.message); process.exit(1); });
}
