export async function renderDbbBlock(read) {
const begin = "  // BEGIN GENERATED GND DBB ADAPTER";
const end = "  // END GENERATED GND DBB ADAPTER";
const sources = [
	"src/import/parsers/technet/gndEdit/gnd/extractGndDbb.js",
	"src/import/parsers/technet/gndEdit/parseGND_DBB.js",
];
const inline = [];
for (const source of sources) {
	const text = await read(source);
	const body = text.replace(/^import .*;\r?\n/gm, "").replace(/^export /gm, "").trim();
	if (/^import |^export /m.test(body)) throw new Error(`Unsupported module declaration: ${source}`);
	inline.push(`// ${source}\n${body}`);
}
const block = `${begin}\n  // Generated by tools/sync-technet-dbb.mjs; do not edit this block.\n  const gndDbbAdapter = (() => {\n${inline.join("\n\n").split("\n").map((line) => line ? `    ${line.replace(/^\t+/, (tabs) => "  ".repeat(tabs.length))}` : "").join("\n")}\n    return { parseGND_DBB, looksLikeGndDbb };\n  })();\n${end}`;
return block;
}

